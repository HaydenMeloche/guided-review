import { addedText, removedText } from '../diff/lines.js';
import { matchGlob } from '../util/glob.js';
import { DEPENDENCY_MANIFEST, TOOLCHAIN_FILE } from './dependencies.js';
import { isImportLine } from './imports.js';
import { isLockfile, summarizeLockfile } from './lockfile.js';
import { DOC_PATH, PROTOBUF_OUTPUT } from './patterns.js';
import { isTestPath } from './testPaths.js';
import type { DiffFile, FileKind, Hunk, RepoConfig } from '../types.js';

interface ClassifyContext {
  gitattributes: string;
  readHead: (p: string) => string | undefined;
  config: RepoConfig;
}

interface AttrRule {
  pattern: string;
  generated?: boolean;
  vendored?: boolean;
}

function parseGitattributes(text: string): AttrRule[] {
  const rules: AttrRule[] = [];
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const [pattern, ...attrs] = line.split(/\s+/);
    const rule: AttrRule = { pattern };
    for (const a of attrs) {
      const set = (name: string): boolean | undefined => {
        if (a === name || a === `${name}=true` || a === `${name}=1`) return true;
        if (a === `-${name}` || a === `!${name}` || a === `${name}=false` || a === `${name}=0`) return false;
        return undefined;
      };
      const g = set('linguist-generated');
      if (g !== undefined) rule.generated = g;
      const v = set('linguist-vendored');
      if (v !== undefined) rule.vendored = v;
    }
    if (rule.generated !== undefined || rule.vendored !== undefined) rules.push(rule);
  }
  return rules;
}

function attrFor(rules: AttrRule[], path: string, key: 'generated' | 'vendored'): boolean | undefined {
  let out: boolean | undefined;
  for (const r of rules) if (r[key] !== undefined && matchGlob(r.pattern, path)) out = r[key];
  return out;
}

const VENDORED_DIRS = /(^|\/)(vendor|third_party|third-party|node_modules|bower_components)\//;
const GENERATED_PATHS: [RegExp, string][] = [
  [/(^|\/)__generated__\//, 'codegen output directory'],
  [/(^|\/)generated\//, 'codegen output directory'],
  [PROTOBUF_OUTPUT, 'protobuf output'],
  [/\.gen\.[a-z]+$|\.generated\.[a-z]+$|_gen\.go$|\.g\.dart$|\.freezed\.dart$/, 'generated file name'],
  [/(^|\/)dist\//, 'build output (dist/)'],
  [/\.min\.(js|css)$/, 'minified build output'],
  [/(^|\/)zz_generated[^/]*\.go$/, 'generated file name'],
  [/(^|\/)build\/generated(-sources)?\/|(^|\/)target\/generated-sources\//, 'build output (generated sources)'],
  [/Generated\.(kt|java)$|_Factory\.java$|_MembersInjector\.java$|(^|\/)mock_[^/]*\.go$|(^|\/)mocks?\/[^/]*\.go$/, 'generated file name'],
];
const SNAPSHOT = /(^|\/)__snapshots__\/|\.snap$/;
const GENERATED_HEADER = /@generated|DO NOT EDIT|Code generated|auto-generated|autogenerated|This file was generated|THIS FILE IS GENERATED/i;

const TEST_IMPORT =
  /from\s+['"](vitest|jest|@jest\/globals|mocha|chai|node:test|@testing-library\/[^'"]+|ava|tap|uvu|@playwright\/test|cypress)['"]|require\(['"](mocha|chai|jest|tap|node:test)['"]\)|^\s*import\s+pytest|^\s*import\s+unittest|^\s*import\s+(org\.junit|io\.kotest|kotlin\.test|io\.mockk|org\.mockito)\.|import\s+"testing"|^\s*describe\(|^\s*it\(/m;
const NATIVE_TEST_IMPORT = /^\s*#include\s*[<"](?:gtest\/gtest\.h|catch2\/[^>"]+)[>"]|^\s*(?:TEST|TEST_F|TEST_CASE)\s*\(/m;

// The first match wins, so specific files come before the generic extensions.
const CONFIG_PATHS: [RegExp, string][] = [
  [DOC_PATH, 'documentation'],
  [/(^|\/)\.github\//, 'CI configuration'],
  [/(^|\/)(\.gitlab-ci\.yml|\.circleci\/|Jenkinsfile|\.buildkite\/|azure-pipelines\.yml|\.travis\.yml)/, 'CI configuration'],
  [/(^|\/)Dockerfile[^/]*$|(^|\/)docker-compose[^/]*\.ya?ml$|\.dockerignore$/, 'container configuration'],
  [/\.tf$|\.tfvars$|\.hcl$/, 'Terraform'],
  [/(^|\/)tsconfig[^/]*\.json$|(^|\/)jsconfig[^/]*\.json$/, 'TypeScript configuration'],
  [DEPENDENCY_MANIFEST, 'package manifest'],
  [/(^|\/)go\.work$/, 'package manifest'],
  [TOOLCHAIN_FILE, 'toolchain version'],
  [/(^|\/)settings\.gradle(\.kts)?$|(^|\/)gradle\.properties$|(^|\/)gradle\/|(^|\/)gradlew(\.bat)?$|(^|\/)buildSrc\//, 'Gradle/Maven build configuration'],
  [/(^|\/)setup\.py$|(^|\/)Pipfile$|(^|\/)tox\.ini$/, 'Python packaging'],
  [/(^|\/)Makefile$|(^|\/)CODEOWNERS$/, 'build configuration'],
  [/\.config\.(js|ts|mjs|cjs|mts|cts|json)$/, 'tool configuration'],
  [/(^|\/)\.(eslintrc|prettierrc|babelrc|npmrc|editorconfig|gitignore|gitattributes)[^/]*$/, 'tool configuration'],
  [/(^|\/)\.env\.[^/]*$|(^|\/)\.env$/, 'environment configuration'],
  [/\.ya?ml$/, 'YAML configuration'],
  [/\.toml$|\.ini$|\.cfg$/, 'configuration file'],
  [/\.jsonc?$/, 'JSON configuration'],
];

function changed(h: Hunk): { adds: string[]; dels: string[] } {
  return { adds: addedText(h), dels: removedText(h) };
}

// Whitespace, line-final semicolons and trailing commas are what formatters change.
const squash = (lines: string[]) =>
  lines
    .map((l) => l.replace(/;\s*$/, ''))
    .join('')
    .replace(/\s+/g, '')
    .replace(/,([)\]}])/g, '$1');

function isFormattingOnly(h: Hunk): boolean {
  const { adds, dels } = changed(h);
  if (!adds.length && !dels.length) return false;
  return squash(adds) === squash(dels);
}

function isReorderOnly(h: Hunk): { reorder: boolean; imports: boolean } {
  const { adds, dels } = changed(h);
  if (!adds.length || adds.length !== dels.length) return { reorder: false, imports: false };
  const a = adds.map((s) => s.trim()).sort();
  const d = dels.map((s) => s.trim()).sort();
  const reorder = a.every((x, i) => x === d[i]);
  return { reorder, imports: reorder && adds.every((l) => isImportLine(l) || !l.trim()) };
}

function headLines(f: DiffFile, hunks: Hunk[], ctx: ClassifyContext): string {
  const content = f.status === 'deleted' ? undefined : ctx.readHead(f.path);
  if (content !== undefined) return content.split('\n').slice(0, 5).join('\n');
  const first = hunks.find((h) => (f.status === 'deleted' ? h.oldStart : h.newStart) <= 1);
  if (!first) return '';
  const want = f.status === 'deleted' ? 'del' : 'add';
  return first.lines
    .filter((l) => l.kind === want || l.kind === 'ctx')
    .slice(0, 5)
    .map((l) => l.text)
    .join('\n');
}

function vendoredSummary(f: DiffFile, hunks: Hunk[]): string {
  const ver = /(?:"version"\s*:\s*"|^\s*version\s*[=:]\s*"?|\bVersion:\s*|\bv)(\d+\.\d+(?:\.\d+)?[\w.-]*)/i;
  let from: string | undefined;
  let to: string | undefined;
  for (const h of hunks) {
    for (const l of h.lines) {
      const m = l.text.match(ver);
      if (!m) continue;
      if (l.kind === 'del' && !from) from = m[1];
      if (l.kind === 'add' && !to) to = m[1];
    }
  }
  const pathVer = f.path.match(/@v?(\d+\.\d+[\w.-]*)/)?.[1];
  const oldPathVer = f.oldPath?.match(/@v?(\d+\.\d+[\w.-]*)/)?.[1];
  from ??= oldPathVer;
  to ??= pathVer;
  if (from && to && from !== to) return `vendored: version ${from} → ${to}`;
  if (to && f.status === 'added') return `vendored: added at ${to}`;
  return `vendored: +${f.additions} −${f.deletions} lines`;
}

function generatedSummary(f: DiffFile, hunks: Hunk[], reason: string): string {
  if (isLockfile(f.path)) return summarizeLockfile(f.path, hunks);
  if (SNAPSHOT.test(f.path)) return `snapshot: +${f.additions} −${f.deletions} lines (${reason})`;
  if (f.status === 'added') return `${f.additions} generated lines added (${reason})`;
  if (f.status === 'deleted') return `${f.deletions} generated lines removed (${reason})`;
  return `${f.additions + f.deletions} generated lines changed, +${f.additions} −${f.deletions} (${reason})`;
}

function setKind(f: DiffFile, kind: FileKind, reason: string) {
  f.kind = kind;
  f.kindReason = reason;
}

function classifyFile(f: DiffFile, hunks: Hunk[], ctx: ClassifyContext, attrs: AttrRule[]): void {
  const p = f.path;
  f.summary = undefined;

  // 1. Repo rules win.
  const rule = ctx.config.kinds.find((r) => matchGlob(r.pattern, p));
  if (rule) {
    setKind(f, rule.kind, `repo rule ${rule.pattern}`);
  } else if (attrFor(attrs, p, 'vendored') === true || (VENDORED_DIRS.test(p) && attrFor(attrs, p, 'vendored') !== false)) {
    setKind(f, 'vendored', attrFor(attrs, p, 'vendored') ? 'linguist-vendored in .gitattributes' : 'vendored directory');
  } else if (attrFor(attrs, p, 'generated') === true) {
    setKind(f, 'generated', 'linguist-generated in .gitattributes');
  } else if (isLockfile(p)) {
    setKind(f, 'generated', 'lockfile');
  } else if (SNAPSHOT.test(p)) {
    setKind(f, 'generated', 'test snapshot');
  } else {
    const gp = attrFor(attrs, p, 'generated') === false ? undefined : GENERATED_PATHS.find(([re]) => re.test(p));
    if (gp) setKind(f, 'generated', gp[1]);
    else if (!f.binary && attrFor(attrs, p, 'generated') !== false && GENERATED_HEADER.test(headLines(f, hunks, ctx))) {
      setKind(f, 'generated', 'generated-code header');
    } else if (isTestPath(p, ctx.config.testPatterns)) {
      setKind(f, 'test', 'test file path');
    } else {
      const cp = CONFIG_PATHS.find(([re]) => re.test(p));
      if (cp) setKind(f, 'config', cp[1]);
      else {
        const head = f.status === 'deleted' || f.binary ? undefined : ctx.readHead(p);
        if (head && (TEST_IMPORT.test(head) || NATIVE_TEST_IMPORT.test(head))) setKind(f, 'test', 'imports a test framework');
        else setKind(f, 'logic', 'hand-written code');
      }
    }
  }

  // 2. Mechanical changes (unless a repo rule or generated/vendored already decided).
  if (!rule && (f.kind === 'logic' || f.kind === 'test' || f.kind === 'config')) {
    if ((f.status === 'renamed' || f.oldPath) && hunks.length === 0) {
      const sameDir = f.oldPath && f.oldPath.slice(0, f.oldPath.lastIndexOf('/')) === p.slice(0, p.lastIndexOf('/'));
      setKind(f, 'mechanical', sameDir ? 'rename' : 'move');
      f.summary = `${sameDir ? 'renamed' : 'moved'} from ${f.oldPath}, contents unchanged`;
    } else if (hunks.length) {
      let fmt = 0;
      let imp = 0;
      let reorder = 0;
      for (const h of hunks) {
        if (isFormattingOnly(h)) fmt++;
        else {
          const r = isReorderOnly(h);
          if (r.imports) imp++;
          else if (r.reorder) reorder++;
        }
      }
      if (fmt + imp + reorder === hunks.length && (fmt || imp)) {
        const what = [fmt && 'formatting', imp && 'import order', reorder && 'line order'].filter(Boolean).join(' and ');
        setKind(f, 'mechanical', `${what} only`);
        f.summary = (f.oldPath ? `renamed from ${f.oldPath}; ` : '') + `${what} only`;
      }
    }
  }

  if (f.kind === 'generated') f.summary = generatedSummary(f, hunks, f.kindReason);
  else if (f.kind === 'vendored') f.summary = vendoredSummary(f, hunks);
  else if (f.kind === 'config' && /\.(jsonc?|ya?ml)$/i.test(p) && !f.summary) {
    const keys = [
      ...new Set(
        hunks
          .flatMap((h) => h.lines)
          .filter((l) => l.kind !== 'ctx')
          .map((l) => /^\s*(?:-\s*)?["']?([\w.-]+)["']?\s*:/.exec(l.text)?.[1])
          .filter((key): key is string => !!key),
      ),
    ];
    f.summary = keys.length ? `Changed keys: ${keys.slice(0, 5).join(', ')}${keys.length > 5 ? ` (+${keys.length - 5} more)` : ''}` : 'Configuration values changed';
  } else if (f.binary && !f.summary) f.summary = `binary file ${f.status}`;
}

export function classifyFiles(files: DiffFile[], hunks: Record<string, Hunk>, ctx: ClassifyContext): void {
  const attrs = parseGitattributes(ctx.gitattributes);
  for (const f of files) classifyFile(f, f.hunkIds.map((id) => hunks[id]).filter(Boolean), ctx, attrs);
}
