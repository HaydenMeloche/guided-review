function write(root: string, files: Record<string, string>): void {
  for (const [file, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), text);
  }
}

// Writes the demo repository afresh at `root` (edits from an earlier run are dropped): `main`
// with the shop, and the demo branch checked out on top with the change.
export async function writeDemoRepo(root: string): Promise<void> {
  fs.rmSync(root, { recursive: true, force: true });
  fs.mkdirSync(root, { recursive: true });
  const run = (...args: string[]) => git(root, ['-c', 'commit.gpgsign=false', '-c', 'core.autocrlf=false', ...args], { env: ENV });
  await run('init', '-q', '-b', 'main');
  write(root, BASE);
  await run('add', '-A');
  await run('commit', '-q', '-m', 'Price orders');
  // origin/HEAD names the default branch, so nothing asks GitHub for it.
  await run('update-ref', 'refs/remotes/origin/main', 'HEAD');
  await run('symbolic-ref', 'refs/remotes/origin/HEAD', 'refs/remotes/origin/main');
  await run('checkout', '-q', '-b', DEMO_BRANCH);
  write(root, HEAD);
  await run('add', '-A');
  await run('commit', '-q', '-m', TITLE);
}

// What a model would write about the demo, written out so the demo shows a narrated tour without
// one. Chapters and hunks are found by file, since their ids come from the build.
export function demoNarration(tour: Tour): CannedNarration {
  const hunkIn = (file: string) => tour.files.find((f) => f.path === file)?.hunkIds[0];
  const chapterOf = (file: string) => {
    const id = hunkIn(file);
    return tour.chapters.find((c) => id && c.hunkIds.includes(id))?.id;
  };
  const hunk = (file: string, narration: string, risk?: { risk: number; riskReason: string }) => {
    const id = hunkIn(file);
    return id ? [{ id, narration, citesCode: true, ...risk }] : [];
  };
  const chapter = (file: string, hunks: ChapterResult['hunks']) => {
    const id = chapterOf(file);
    return id ? [{ id, result: { hunks } }] : [];
  };
  const named = (file: string, title: string, summary: string) => {
    const id = chapterOf(file);
    return id ? [{ id, title, summary }] : [];
  };
  return {
    briefing: {
      intent:
        'Lets customers enter a discount code at checkout. POST /orders passes the code to `createOrder`, and `quote` looks it up and takes the discount off the subtotal before tax. Alongside it, `formatReceipt` moves to its own module, zod is added, and the generated request type gains the field.',
      // In reading order: the entry point first, then what it calls, then the move.
      chapters: [
        ...named('src/routes.ts', 'Taking a code at POST /orders', 'The handler reads discountCode from the request body and passes it on as it came.'),
        ...named(
          'src/pricing.ts',
          'Pricing an order with a discount',
          'quote looks the code up, checks the order’s minimum, and takes the percentage off the subtotal before tax; createOrder passes the code through and keeps it on the order.',
        ),
        ...named('src/receipt.ts', 'formatReceipt moves to receipt.ts', 'A move with no edits: orders.ts loses the function, receipt.ts gains it line for line, and admin.ts imports it from there.'),
      ],
    },
    chapters: [
      ...chapter('src/routes.ts', [
        ...hunk(
          'src/routes.ts',
          'The handler now passes `req.body.discountCode` to `createOrder`. Nothing here checks that it is a string, or how long it is, so whatever the client sends reaches the discount lookup.',
          { risk: 2, riskReason: 'request input reaches pricing unvalidated' },
        ),
      ]),
      ...chapter('src/pricing.ts', [
        ...hunk(
          'src/orders.ts',
          '`createOrder` takes an optional discount code, passes it to `quote`, and keeps it on the order. The removed `formatReceipt` above it is not gone: it moved to src/receipt.ts unchanged, as the marks on its lines say.',
        ),
        ...hunk(
          'src/pricing.ts',
          '`DISCOUNTS` lists three codes, each with a percentage and a minimum subtotal. `discountAmount` upper-cases the code, so `welcome10` works, and returns 0 for an unknown code or an order under the minimum. `quote` takes the discount off before tax, so tax is charged on what the customer pays.',
          { risk: 2, riskReason: 'STAFF50 takes half off any order, and any customer can type it' },
        ),
        ...hunk('test/pricing.test.ts', 'The new test covers one valid code in lowercase. Nothing tests an unknown code or an order under BULK15’s minimum: the two ways `discountAmount` returns 0.'),
      ]),
      ...chapter('src/receipt.ts', [...hunk('src/receipt.ts', 'The `formatReceipt` removed from src/orders.ts, line for line. Only where it lives changed.')]),
      ...chapter('package.json', [
        ...hunk(
          'package.json',
          'Adds zod 3.23.8, a schema validation library, and bumps the package to 0.4.0; the lockfile adds zod and nothing else. No code in this change imports zod yet, so it may be meant for checking the order request.',
        ),
      ]),
    ],
  };
}

// The demo, ready to open as a preview: its own title and description in place of the branch's.
export async function demoPreview(root = path.join(grHome(), 'demo')): Promise<LocalPreview> {
  await writeDemoRepo(root);
  const p = await localPreview(root, DEMO_REPO);
  return { ...p, pr: { ...p.pr, title: `${TITLE} (demo)`, body: BODY } };
}
