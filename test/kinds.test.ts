import { describe, expect, it } from 'vitest';
import { parseUnifiedDiff } from '../src/diff/parse.js';
import { classifyFiles } from '../src/analysis/kinds.js';
import { checkGeneratedSync } from '../src/analysis/generatedSync.js';
import type { Hunk, RepoConfig } from '../src/types.js';

function file(path: string, body: string, header = 'index 1..2 100644') {
  return `diff --git a/${path} b/${path}\n${header}\n--- a/${path}\n+++ b/${path}\n${body}`;
}

function classify(diff: string, opts: { gitattributes?: string; heads?: Record<string, string>; config?: RepoConfig } = {}) {
  const { files, hunks } = parseUnifiedDiff(diff);
  const map: Record<string, Hunk> = Object.fromEntries(hunks.map((h) => [h.id, h]));
  classifyFiles(files, map, {
    gitattributes: opts.gitattributes ?? '',
    readHead: (p) => opts.heads?.[p],
    config: opts.config ?? { kinds: [], testPatterns: [], checklists: [] },
  });
  return { files, map };
}

const logicBody = '@@ -1,2 +1,2 @@\n const a = 1;\n-const b = 2;\n+const b = 3;\n';

describe('classifyFiles', () => {
  it('summarizes changed JSON and YAML keys', () => {
    const diff = [file('settings.json', '@@ -1 +1 @@\n-  "timeout": 10\n+  "timeout": 20\n'), file('settings.yaml', '@@ -1 +1 @@\n-  retries: 1\n+  retries: 3\n')].join('\n');
    const { files } = classify(diff);
    expect(files.map((f) => [f.kind, f.summary])).toEqual([
      ['config', 'Changed keys: timeout'],
      ['config', 'Changed keys: retries'],
    ]);
  });

  it('classifies by path', () => {
    const diff = [
      'src/app.ts',
      'src/app.test.ts',
      'vendor/lib/x.go',
      'third_party/foo/a.c',
      '.github/workflows/ci.yml',
      'Dockerfile',
      'infra/main.tf',
      'src/__generated__/types.ts',
      'api/user.pb.go',
      'src/__snapshots__/app.test.ts.snap',
      'tsconfig.json',
      'pkg/server_test.go',
      'tests/test_api.py',
      'src/store_test.cpp',
      'settings.json',
      'settings.yaml',
    ]
      .map((p) => file(p, logicBody))
      .join('\n');
    const { files } = classify(diff);
    expect(Object.fromEntries(files.map((f) => [f.path, f.kind]))).toEqual({
      'src/app.ts': 'logic',
      'src/app.test.ts': 'test',
      'vendor/lib/x.go': 'vendored',
      'third_party/foo/a.c': 'vendored',
      '.github/workflows/ci.yml': 'config',
      Dockerfile: 'config',
      'infra/main.tf': 'config',
      'src/__generated__/types.ts': 'generated',
      'api/user.pb.go': 'generated',
      'src/__snapshots__/app.test.ts.snap': 'generated',
      'tsconfig.json': 'config',
      'pkg/server_test.go': 'test',
      'tests/test_api.py': 'test',
      'src/store_test.cpp': 'test',
      'settings.json': 'config',
      'settings.yaml': 'config',
    });
  });

  it('honours .gitattributes, headers, test imports and repo rules', () => {
    const diff = ['src/client.ts', 'src/schema.ts', 'src/checks.ts', 'src/legacy/x.ts', 'src/keep.gen.ts'].map((p) => file(p, logicBody)).join('\n');
    const { files } = classify(diff, {
      gitattributes: 'src/client.ts linguist-generated=true\n*.gen.ts -linguist-generated\n',
      heads: {
        'src/schema.ts': '// Code generated by sqlc. DO NOT EDIT.\nexport {}',
        'src/checks.ts': "import { describe, it } from 'vitest';\n",
      },
      config: { kinds: [{ pattern: 'src/legacy/**', kind: 'vendored' }], testPatterns: [], checklists: [] },
    });
    const k = Object.fromEntries(files.map((f) => [f.path, [f.kind, f.kindReason]]));
    expect(k['src/client.ts']).toEqual(['generated', 'linguist-generated in .gitattributes']);
    expect(k['src/schema.ts']).toEqual(['generated', 'generated-code header']);
    expect(k['src/checks.ts']).toEqual(['test', 'imports a test framework']);
    expect(k['src/legacy/x.ts']).toEqual(['vendored', 'repo rule src/legacy/**']);
    expect(k['src/keep.gen.ts'][0]).toBe('logic');
  });

  it('detects mechanical changes', () => {
    const rename = 'diff --git a/src/a.ts b/lib/a.ts\nsimilarity index 100%\nrename from src/a.ts\nrename to lib/a.ts\n';
    const fmt = file('src/fmt.ts', '@@ -1 +1,3 @@\n-function f(a,b){return a+b}\n+function f(a, b) {\n+  return a + b;\n+}\n');
    const imports = file('src/imp.ts', "@@ -1,3 +1,3 @@\n-import b from './b';\n-import a from './a';\n+import a from './a';\n+import b from './b';\n const x = 1;\n");
    const { files } = classify([rename, fmt, imports, file('src/real.ts', logicBody)].join('\n'));
    const k = Object.fromEntries(files.map((f) => [f.path, [f.kind, f.summary]]));
    expect(k['lib/a.ts']).toEqual(['mechanical', 'moved from src/a.ts, contents unchanged']);
    expect(k['src/fmt.ts']).toEqual(['mechanical', 'formatting only']);
    expect(k['src/imp.ts']).toEqual(['mechanical', 'import order only']);
    expect(k['src/real.ts'][0]).toBe('logic');
  });

  it('summarizes lockfiles and vendored version changes', () => {
    const lock = file(
      'package-lock.json',
      `@@ -10,8 +10,12 @@
     "node_modules/react": {
-      "version": "18.2.0",
+      "version": "19.0.0",
       "license": "MIT"
     },
+    "node_modules/zod": {
+      "version": "3.23.8",
+      "license": "MIT"
+    },
-    "node_modules/left-pad": {
-      "version": "1.3.0"
-    },
     "node_modules/lodash": {
-      "version": "4.17.20",
+      "version": "4.17.21",
`,
    );
    const vend = file('vendor/github.com/foo/bar/VERSION', '@@ -1 +1 @@\n-v1.2.0\n+v1.3.0\n');
    const { files } = classify([lock, vend].join('\n'));
    expect(files[0].kind).toBe('generated');
    expect(files[0].summary).toBe('+1 added (zod), -1 removed (left-pad), major: react 18.2.0→19.0.0, 1 minor/patch bump');
    expect(files[1].summary).toBe('vendored: version 1.2.0 → 1.3.0');
  });
});

describe('checkGeneratedSync', () => {
  it('flags schema changes without regenerated output and the reverse', () => {
    const { files, map } = classify([file('schema.graphql', logicBody), file('api/user.proto', logicBody), file('api/user.pb.go', logicBody), file('src/__generated__/x.ts', logicBody)].join('\n'));
    const flags = checkGeneratedSync(files, map);
    // graphql schema changed and src/__generated__ changed => in sync; proto + pb.go => in sync
    expect(flags.filter((f) => f.kind === 'generated-out-of-sync')).toEqual([]);

    const only = classify([file('schema.graphql', logicBody), file('api/user.pb.go', logicBody)].join('\n'));
    const msgs = checkGeneratedSync(only.files, only.map).map((f) => f.message);
    expect(msgs.some((m) => m.startsWith('GraphQL schema changed'))).toBe(true);
    expect(msgs.some((m) => m.startsWith('generated code changed without its source: api/user.pb.go'))).toBe(true);
  });

  it('flags dependency edits without a lockfile, ignoring script-only edits', () => {
    const dep = classify(file('package.json', '@@ -5,3 +5,4 @@\n   "dependencies": {\n+    "zod": "^3.23.0",\n     "react": "^19.0.0"\n   }\n'));
    expect(checkGeneratedSync(dep.files, dep.map)[0].message).toMatch(/package\.json changed but no lockfile/);
    const script = classify(file('package.json', '@@ -2,3 +2,3 @@\n   "scripts": {\n-    "test": "jest"\n+    "test": "vitest"\n   }\n'));
    expect(checkGeneratedSync(script.files, script.map)).toEqual([]);
  });
});
